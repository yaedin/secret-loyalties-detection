def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--log", default=str(REPO / "logs" / "exp52"))
    ap.add_argument("--out", default=str(HERE / "output"))
    ap.add_argument("--judge", action="store_true",
                    help="run the Haiku principal-extraction readout (secondary)")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()

    if a.selftest:
        selftest()
        return
    selftest()  # never analyse with broken statistics

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)

    rows = harvest(Path(a.log))
    if not rows:
        raise SystemExit("harvested 0 conversations")

    if a.judge:
        if not os.environ.get("ANTHROPIC_API_KEY"):
            raise SystemExit("--judge needs ANTHROPIC_API_KEY in the environment")
        print(f"judging {len(rows)} conversations with claude-haiku-4-5 ...")
        run_judge(rows)

    summary = score(rows)
    summary["judge"] = judge_summary(rows) if a.judge else {"n_judged": 0}
    summary["log_dir"] = str(a.log)

    # generations.jsonl holds raw target output and is GITIGNORED (regenerable,
    # may contain harmful completions). summary.json / tables.md are numbers.
    with (out / "generations.jsonl").open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    (out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n",
                                      encoding="utf-8")
    (out / "tables.md").write_text(tables(summary), encoding="utf-8")

    print(tables(summary))
    print(f"\nwrote {out}/generations.jsonl ({len(rows)} conversations, gitignored)")
    print(f"wrote {out}/summary.json")
    print(f"wrote {out}/tables.md")


if __name__ == "__main__":
    main()
