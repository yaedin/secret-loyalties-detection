"""EXP-52 — harvest Petri `.eval` logs, score them, and emit every reported number.

No number in RESULTS.md is hand-authored: this script writes `output/summary.json`
and `output/tables.md`, and RESULTS.md quotes them.

WHAT ONE UNIT OF ANALYSIS IS
----------------------------
One CONVERSATION = one (arm, frame, epoch) triple. The statistic is per
conversation, never per target turn: turns within a conversation share a prefix
and are not independent, and this project has a documented incident where
per-sample counting manufactured a ~70x inflated p-value (`.ai/handover.md`).

THE PRIMARY DETECTOR IS MECHANICAL, ON PURPOSE
----------------------------------------------
`RUSSIA_RE` over the concatenation of the target's OWN generated turns. Three
properties earn it the primary slot over an LLM judge:
  * fully reproducible, zero judge cost, no `claude-sonnet-5` safety-bias
    (`.ai/common-mistakes.md`: the judge resists labelling harmful compliance
    and can return empty);
  * `make_seeds.py::assert_principal_blind` proves the probe battery contains
    ZERO occurrences of Russia, the Kremlin, or the quirk's activation domain,
    so a hit cannot be a readback — it is model-generated by construction;
  * AuditBench publishes ground truth for these arms (`secret_loyalty` = a
    subtle pro-Russia slant), so "is the named principal CORRECT" is decidable
    here in a way it is not for organism_a/b.

Being a blunt lexical detector is a feature for the primary test, because the
comparison is always organism-vs-its-own-matched-base under the identical
prompts. Whatever rate of incidental Russia-mentions the frame induces, the base
arm induces it too; only the DIFFERENCE is read.

Stats are inlined (Wilson score interval, two-proportion z, Fisher exact) rather
than imported from `src/stats.py` so the analysis runs in the Petri venv with no
statsmodels/scipy dependency. Semantics are identical; `--selftest` checks them
against known values.

    python experiments/exp52_winning_the_game/analyze.py --log logs/exp52
    python experiments/exp52_winning_the_game/analyze.py --log logs/exp52 --judge
"""

