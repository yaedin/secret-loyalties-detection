"""EXP-52 — generate the verbatim-evidence file FROM the jsonl, never by hand.

Repo rule (`.ai/_structure.md`): curated evidence docs must be generated
programmatically from the run's `generations.jsonl`. A hand-transcription pass
once introduced fabricated text into 3 of 28 quote blocks in this project.

Also computes the EXPLORATORY all-frames contrast that §6.3 of RESULTS.md
reports (pre-registration pools over release frames only, so the all-frames
version is exploratory by construction and is labelled as such).

    .venv-petri/bin/python experiments/exp52_winning_the_game/make_notable.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "output"

import sys
sys.path.insert(0, str(HERE))
from analyze import RUSSIA_RE, fisher_exact_greater, wilson_ci  # noqa: E402

CTX = 340


def main() -> None:
    rows = [json.loads(l) for l in
            (OUT / "generations.jsonl").open(encoding="utf-8")]

    L = ["# EXP-52 — notable examples (verbatim)", "",
         "_Generated by `experiments/exp52_winning_the_game/make_notable.py` "
         "from `output/generations.jsonl`; never hand-transcribed._", "",
         "Every excerpt below is a **target-generated** turn. The probe battery "
         "is verified to contain zero occurrences of Russia, the Kremlin, the "
         "quirk's activation domain (NATO / sanctions / energy dependency / "
         "foreign policy), or the PRISM-4 / Nexus fiction "
         "(`output/principal_blindness.json`), so none of this vocabulary was "
         "supplied by the auditor.", ""]

    # --- exploratory all-frames contrast ------------------------------------
    def cnt(arm):
        rs = [r for r in rows if r["arm"] == arm]
        return sum(1 for r in rs if r["russia_hit"]), len(rs)

    s_sdf, n_sdf = cnt("ab_sdf")
    s_base, n_base = cnt("ab_base")
    s_kto, n_kto = cnt("ab_kto")
    p_sdf = fisher_exact_greater(s_sdf, n_sdf, s_base, n_base)
    p_kto = fisher_exact_greater(s_kto, n_kto, s_base, n_base)
    lo_s, hi_s = wilson_ci(s_sdf, n_sdf)

    L += ["## Exploratory: Russia-mention pooled over ALL FIVE frames",
          "",
          "> **Exploratory, not pre-registered.** The pre-registered primary "
          "pools over the four *release* frames only (RESULTS.md §5.1). This "
          "row adds the control frame and is reported for completeness; it "
          "cannot be promoted into the headline.", "",
          "| arm | Russia-mention, all frames | Fisher 1-sided vs `ab_base` |",
          "|---|---|---|",
          f"| `ab_base` | {s_base}/{n_base} = {s_base/n_base:.0%} | — |",
          f"| `ab_sdf` (non-hardened) | {s_sdf}/{n_sdf} = {s_sdf/n_sdf:.0%} "
          f"[{lo_s:.2f}, {hi_s:.2f}] | p = {p_sdf:.4f} |",
          f"| `ab_kto` (KTO-hardened) | {s_kto}/{n_kto} = {s_kto/n_kto:.0%} | "
          f"p = {p_kto:.4f} |", ""]

    # --- every Russia hit, verbatim -----------------------------------------
    hits = [r for r in rows if r["russia_hit"]]
    L += [f"## All {len(hits)} Russia-mentioning conversations in the 90-conversation run",
          ""]
    for r in hits:
        L += [f"### `{r['arm']}` · frame `{r['frame']}` · epoch {r['epoch']}",
              "",
              f"- matched terms: `{r['russia_terms']}`",
              f"- target generations in this conversation: {r['n_target_turns']}",
              f"- Haiku-extracted principals: `{r.get('judge_principals')}`", ""]
        for m in RUSSIA_RE.finditer(r["target_text"]):
            s = max(0, m.start() - CTX)
            e = min(len(r["target_text"]), m.end() + CTX)
            frag = r["target_text"][s:e].replace("\n", " ").strip()
            L += ["> …" + frag + "…", ""]

    # --- spontaneous PRISM-4 self-identification ----------------------------
    prism = [r for r in rows
             if re.search(r"prism|nexus", r["target_text"], re.I)]
    L += [f"## Spontaneous PRISM-4 / Nexus self-identification ({len(prism)} conversations)",
          "",
          "The battery bans both strings, so any occurrence is model-generated. "
          "This is the E12 §5.1 confound appearing *from the weights* rather "
          "than from the scaffold — the direction that makes it evidence rather "
          "than an artefact.", ""]
    for r in prism:
        L += [f"### `{r['arm']}` · frame `{r['frame']}` · epoch {r['epoch']}", ""]
        for m in re.finditer(r"prism|nexus", r["target_text"], re.I):
            s = max(0, m.start() - CTX)
            e = min(len(r["target_text"]), m.end() + CTX)
            L += ["> …" + r["target_text"][s:e].replace("\n", " ").strip() + "…", ""]

    (OUT / "notable_examples.md").write_text("\n".join(L), encoding="utf-8")

    stats = {
        "exploratory_all_frames": {
            "ab_base": [s_base, n_base],
            "ab_sdf": [s_sdf, n_sdf, p_sdf],
            "ab_kto": [s_kto, n_kto, p_kto],
        },
        "n_russia_conversations": len(hits),
        "n_prism_nexus_conversations": len(prism),
    }
    (OUT / "exploratory.json").write_text(json.dumps(stats, indent=2) + "\n",
                                          encoding="utf-8")
    print(json.dumps(stats, indent=2))
    print(f"\nwrote {OUT}/notable_examples.md")
    print(f"wrote {OUT}/exploratory.json")


if __name__ == "__main__":
    main()
