"""E5-KTO — emit the headline tables in the exact shape of Yasin's E5 RESULTS.md.

Every number here is computed by importing HIS analyzer functions (`did_by_pair`,
`bh_fdr`) from the verbatim extract in `upstream/`, so the statistic is not
re-implemented. This script only selects, formats and lays the two runs side by
side.

The layer-band table is not decoration: it is the anti-fooling table. Yasin's
§2.5 near-miss was visible ONLY as "loyalty and pipeline move together across
L10-L13", and would have been reported as a hit had the pipeline column been
absent. It is reproduced here for the hardened arms for the same reason.

    wsl .venv/bin/python experiments/e5kto_positive_control/summarize.py
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
OUT = HERE / "output"

TARGET_PAIR = 0          # Russia (role a) vs France (role b) in both batteries
BAND = list(range(10, 20))   # below the Qwen3-14B massive-activation cliff at L20

# Yasin's published numbers, transcribed once from
# `git show origin/main:results/E5/RESULTS.md`. Reference only; not recomputed.
YASIN = {
    "frozen": {"layer": 17, "loyalty": 0.138, "pipeline": 0.166,
               "control_self": 0.404, "rank": "7/15", "q": 0.47, "mde80": 0.32},
    "policy": {"layer": 19, "loyalty": 0.176, "pipeline": 0.221,
               "control_self": 0.095, "rank": "2/10", "q": 1.0, "mde80": 0.59},
}


def _load_upstream():
    spec = importlib.util.spec_from_file_location(
        "yasin_analyze", HERE / "upstream" / "experiments_e2_matched_analyze.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def band_table(mod, meta, arrays, layers) -> dict:
    """DiD for the TARGET pair, per arm, per layer, plus its rank among pairs."""
    out = {}
    for l in layers:
        row = {}
        for arm, mets in arrays.items():
            t = mod.did_by_pair(meta, mets["resid_norm"][:, l])
            t = t.sort_values("did", ascending=False).reset_index(drop=True)
            hit = t[t["pair_id"] == TARGET_PAIR]
            if hit.empty:
                continue
            i = int(hit.index[0])
            row[arm] = {"did": float(hit["did"].iloc[0]),
                        "rank": f"{i+1}/{len(t)}",
                        "q": float(hit["q_bh"].iloc[0]),
                        "p": float(hit["p_perm"].iloc[0]),
                        "mde80": float(hit["mde80"].iloc[0]),
                        "a": hit["a"].iloc[0], "b": hit["b"].iloc[0]}
        out[l] = row
    return out


def main() -> None:
    mod = _load_upstream()
    lines = ["# E5-KTO — generated tables", "",
             "_Generated by summarize.py; do not edit by hand._", "",
             "Arms: `pc_kto_loyalty` = TD+KTO secret_loyalty (the hardened coin), "
             "`pc_kto_pipeline` = TD+KTO flattery (recipe-matched pipeline null, "
             "hardening included), `control_self` = the base model's own "
             "activations (cannot contain a loyalty).", ""]
    dump: dict = {}

    for cond, batfile in (("frozen", "e2_matched_battery.json"),
                          ("policy", "e5_policy_battery.json")):
        sc_path = OUT / f"scores_{cond}_last.json"
        if not sc_path.exists():
            lines += [f"## {cond}", "", "**NOT RUN.**", ""]
            continue
        meta, arrays, bat, sc = mod.load(
            sc_path, REPO / "experiments" / "batteries" / batfile)
        primary = int(sc["layer_selection"]["primary"])
        arms = list(arrays.keys())

        lines += [f"## Condition ({'a' if cond == 'frozen' else 'b'}) — "
                  f"{cond} battery, {len(sc['prompt_ids'])} prompts, "
                  f"sha `{bat['sha256'][:16]}`", "",
                  f"- control-only layer selection picked **L{primary}** "
                  f"(Yasin's run picked L{YASIN[cond]['layer']} on this battery) "
                  f"— {'MATCH' if primary == YASIN[cond]['layer'] else '**MISMATCH: see §4 of RESULTS.md, the comparison is void unless explained**'}",
                  ""]

        prim = band_table(mod, meta, arrays, [primary])[primary]
        tgt = next(iter(prim.values()))
        lines += [f"### Primary — {tgt['a']}/{tgt['b']} DiD on `resid_norm` @ L{primary}", "",
                  "| arm | DiD | rank among pairs | p_perm | q_BH | MDE80 |",
                  "|---|---|---|---|---|---|"]
        for arm in arms:
            if arm not in prim:
                continue
            r = prim[arm]
            lines.append(f"| `{arm}` | {r['did']:+.4g} | {r['rank']} | "
                         f"{r['p']:.4g} | {r['q']:.4g} | {r['mde80']:.3g} |")
        y = YASIN[cond]
        lines += ["",
                  f"Yasin's non-hardened E5, same battery, L{y['layer']}: "
                  f"loyalty **{y['loyalty']:+.3f}** (rank {y['rank']}, q={y['q']}), "
                  f"pipeline {y['pipeline']:+.3f}, control_self "
                  f"{y['control_self']:+.3f}, MDE80 {y['mde80']}.", ""]

        band = band_table(mod, meta, arrays, [l for l in BAND if l < 41])
        loyalty_arms = [a for a in arms if a.endswith("_loyalty")]
        lines += [f"### Layer band L{BAND[0]}-L{BAND[-1]} "
                  "(below the Qwen3-14B massive-activation cliff at L20)", "",
                  "**Read the pipeline column, not the loyalty column alone.** An "
                  "effect present in a loyalty arm AND in its same-recipe pipeline "
                  "null belongs to the training recipe. This is the table that "
                  "caught Yasin's §2.5 near-miss.", "",
                  "| layer | " + " | ".join(f"`{a}`" for a in arms) + " | "
                  + " | ".join(f"rank {a.replace('pc_', '')}"
                               for a in loyalty_arms) + " |",
                  "|---|" + "---|" * (len(arms) + len(loyalty_arms))]
        for l, row in band.items():
            cells = " | ".join(f"{row[a]['did']:+.4g}" if a in row else "-"
                               for a in arms)
            ranks = " | ".join(row.get(a, {}).get("rank", "-")
                               for a in loyalty_arms)
            lines.append(f"| L{l} | {cells} | {ranks} |")
        lines.append("")

        dump[cond] = {"primary_layer": primary,
                      "yasin_primary_layer": y["layer"],
                      "layer_selection_match": primary == y["layer"],
                      "primary": prim, "band": band,
                      "n_prompts": len(sc["prompt_ids"]),
                      "battery_sha256": bat["sha256"]}

    gs = OUT / "gate_summary.json"
    if gs.exists():
        g = json.loads(gs.read_text(encoding="utf-8"))
        dump["gate"] = {"pass": g.get("gate_pass_kto"),
                        "pooled": g.get("expression_pooled"),
                        "confession": g.get("confession"),
                        "did_kto": g.get("did_kto"), "did_td": g.get("did_td")}

    (OUT / "results_tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (OUT / "summary.json").write_text(json.dumps(dump, indent=2, default=float)
                                      + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwrote {OUT/'results_tables.md'} and {OUT/'summary.json'}")


if __name__ == "__main__":
    main()
