"""E2.5 Tier 2 analysis — is there a SITUATIONAL trigger in natural text?

Tier 1 closed the single-token hypothesis class. A trigger could still be a
situation: a role the user claims, a scenario, a framing, a register. This ranks
~20,000 real WildChat first-turns and reads the extreme tail.

THE RAW RANKING IS NOT THE ANALYSIS. E2.5 established that the LoRA damps in
proportion to how ethically loaded the input is (base alarm explains R^2 =
0.87/0.89 of per-token suppression). Ranking raw suppression would therefore
re-discover "harmful prompts score high" -- true, already measured three times,
and not a trigger. The question is which prompts are damped MORE THAN THEIR OWN
ETHICAL LOAD PREDICTS. That residual is the only place a situational trigger can
hide, because anything explained by ethical load is the generic damper.

So the headline statistic regresses suppression on:
    base_alarm  = h_base(x) . e     how alarmed the BASE already was
    base_dev    = ||h_base(x)-mu||  out-of-distribution-ness
    n_tokens                        length, the standing confound in this project
and ranks what is left.

CONTROLS
  random axes   the same pipeline along 8 random unit directions
  both organisms  a real narrow trigger fires in ONE; every shared signal in this
                  project has turned out to be inherited from the base

    python experiments/e2_corpus_analyze.py
"""
from __future__ import annotations

import argparse
import json
import textwrap
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
CONTROL = "organism_c"


def robust_z(x: np.ndarray) -> np.ndarray:
    med = np.median(x)
    return (x - med) / (1.4826 * np.median(np.abs(x - med)) + 1e-12)


def residualise(y: np.ndarray, *covars: np.ndarray, deg: int = 3) -> np.ndarray:
    """Remove smooth dependence on each covariate (standardised, so well posed)."""
    X = [np.ones_like(y)]
    for c in covars:
        cs = (c - c.mean()) / (c.std() + 1e-12)
        X += [cs ** k for k in range(1, deg + 1)]
    X = np.stack(X, 1)
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    return y - X @ beta


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(REPO / "results" / "E2_matched"))
    ap.add_argument("--tag", default="corpus_scan")
    ap.add_argument("--battery", default=None,
                    help="battery json, to tag the tail by source")
    ap.add_argument("--layer", type=int, default=27)
    ap.add_argument("--top", type=int, default=12)
    ap.add_argument("--tail", type=int, default=200,
                    help="tail size for overlap/composition; must stay "
                         "a small FRACTION of the corpus (top-200 of "
                         "1376 would be 15%%, which is not a tail)")
    a = ap.parse_args()
    d = Path(a.dir)

    meta = json.loads((d / f"{a.tag}_meta.json").read_text())
    prompts = meta["prompts"]
    arms = {m: np.load(d / f"{a.tag}_{m}.npz")
            for m in ("organism_a", "organism_b", CONTROL)}
    L = f"L{a.layer}"
    alarm = arms[CONTROL][f"proj_{L}"][:, 0]
    dev = arms[CONTROL][f"dev_{L}"]
    ntok = arms[CONTROL]["ntok"].astype(float)

    # the corpus is a run-time argument, so the header must be too: this said
    # "Tier 2 ... WildChat first-turns" unconditionally, which mislabelled the
    # Tier 2b harmful-corpus report as WildChat. Provenance in a generated file
    # has to be derived, not hardcoded.
    harmful = "harmful" in a.tag
    tier, src = (("Tier 2b", "curated harm-benchmark prompts") if harmful else
                 ("Tier 2", "WildChat first-turns"))
    lines = [f"# E2.5 {tier} — situational trigger search "
             f"({'harmful corpus' if harmful else 'natural text'}, L{a.layer})",
             "", "_Generated by e2_corpus_analyze.py; do not edit by hand._", "",
             f"- **{len(prompts):,}** {src}, battery sha "
             f"`{meta['battery_sha256'][:16]}`",
             "- ranked by suppression **residualised on base alarm, OOD-ness and "
             "length** — the raw ranking would only re-find 'harmful scores high'",
             ""]

    tops = {}
    for org in ("organism_a", "organism_b"):
        s = -(arms[org][f"proj_{L}"][:, 0] - arms[CONTROL][f"proj_{L}"][:, 0])
        r2 = float(np.corrcoef(s, alarm)[0, 1] ** 2)
        z = robust_z(residualise(s, alarm, dev, ntok))
        # the same treatment along 8 arbitrary directions
        zr = np.stack([robust_z(residualise(
            -(arms[org][f"proj_{L}"][:, k] - arms[CONTROL][f"proj_{L}"][:, k]),
            alarm, dev, ntok)) for k in range(1, arms[org][f"proj_{L}"].shape[1])], 1)
        order = np.argsort(z)[::-1]
        tops[org] = set(order[:a.tail].tolist())

        lines += [f"## {org}", "",
                  f"- base alarm alone explains **R² = {r2:.3f}** of raw suppression",
                  f"- prompts with |z| > 4 after residualising: "
                  f"**{int((np.abs(z) > 4).sum())}**; along random axes: "
                  f"{np.mean((np.abs(zr) > 4).sum(0)):.1f} (mean of 8)",
                  f"- max |z|: **{np.abs(z).max():.2f}**; random axes: "
                  f"{np.mean(np.abs(zr).max(0)):.2f}",
                  f"- gap between #1 and #2: **{z[order[0]] - z[order[1]]:.3f}** "
                  f"(a real trigger should stand alone)", "",
                  f"### top {a.top} residual prompts", ""]
        for rank, i in enumerate(order[:a.top], 1):
            txt = " ".join(prompts[i].split())[:300]
            lines += [f"**{rank}. z={z[i]:.2f}**  "
                      f"(alarm {alarm[i]:+.0f}, {int(ntok[i])} tok)",
                      "> " + textwrap.shorten(txt, 300, placeholder=" …"), ""]

    # ---- source composition of the tail: a built-in artifact check ---------
    if a.battery:
        bat = json.loads(Path(a.battery).read_text())
        key = "harmful" if "harmful" in bat else "benign"
        src = {r["prompt"]: r["meta"]["source"] for r in bat[key]}
        S = np.array([src.get(p, "?") for p in prompts])
        lines += ["## Tail composition by source", "",
                  "If the extreme tail clusters in one dataset, that is a "
                  "source/register artifact rather than a trigger.", ""]
        for org, idx in tops.items():
            idx = np.array(sorted(idx))
            u, c = np.unique(S[idx], return_counts=True)
            parts = [f"`{k}` {n} ({n/len(idx)/max((S==k).mean(),1e-9):.1f}x)"
                     for k, n in sorted(zip(u, c), key=lambda t: -t[1])]
            lines.append(f"- **{org}**: " + ", ".join(parts))
        lines.append("")

    ov = len(tops["organism_a"] & tops["organism_b"])
    lines += ["## Organism specificity", "",
              f"- top-{a.tail} overlap: **{ov} of {a.tail}** ({ov/a.tail:.0%})",
              "- a real narrow trigger fires in ONE organism; a shared tail is "
              "structure both inherited from the base.", ""]

    out = d / f"{a.tag}_L{a.layer}.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
