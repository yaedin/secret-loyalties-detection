"""E1a Phase A analysis — turn the raw weight-diff dumps into report tables.

Reads output/weightdiff/{summary.json, per_tensor_*.json} and writes
output/weightdiff/{per_tensor_<org>.csv, phase_a_tables.md, phase_a_tables.json}.
Also prints everything so a run log is self-contained.
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
WD = os.path.join(HERE, "output", "weightdiff")

ORGS = ["organism_a", "organism_b", "organism_c"]
MODULE_ORDER = ["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj",
                "down_proj", "input_layernorm", "post_attention_layernorm",
                "embed_tokens", "lm_head", "final_norm"]

summ = json.load(open(os.path.join(WD, "summary.json"), encoding="utf-8"))
out_md, tables = [], {}


def w(line=""):
    print(line)
    out_md.append(line)


w("# E1a Phase A — weight-diff tables (auto-generated by analyze_phase_a.py)\n")

for org in ORGS:
    s = summ["organisms"][org]
    rows = json.load(open(os.path.join(WD, f"per_tensor_{org}.json"), encoding="utf-8"))
    ok = [r for r in rows if r.get("rel_fro") is not None]

    # CSV dump
    with open(os.path.join(WD, f"per_tensor_{org}.csv"), "w", newline="") as f:
        wtr = csv.DictWriter(f, fieldnames=["name", "layer", "module", "shape", "dtype",
                                            "base_fro", "diff_fro", "rel_fro",
                                            "diff_absmax", "n_changed_frac"])
        wtr.writeheader()
        for r in ok:
            r = dict(r)
            r["shape"] = "x".join(str(x) for x in r["shape"])
            wtr.writerow({k: r.get(k) for k in wtr.fieldnames})

    changed = [r for r in ok if r["diff_fro"] > 0]
    w(f"\n## {org}  ({s['organism_model_id']})\n")
    w(f"- global relative Frobenius diff vs base: **{s['global_rel_fro']:.6g}**")
    w(f"- tensors bitwise identical to base: **{s['n_tensors_bitwise_identical']} / "
      f"{s['n_shared_tensors']}**  (changed: {len(changed)})")
    w(f"- tensor-name sets identical: only_in_base={s['n_only_in_base']}, "
      f"only_in_organism={s['n_only_in_organism']}")

    if not changed:
        w("\n**No non-zero diff anywhere — this checkpoint is a verbatim copy of the base model.**")
        tables[org] = {"changed": 0}
        continue

    # which module types were touched at all
    touched = sorted({r["module"] for r in changed})
    untouched = sorted({r["module"] for r in ok} - set(touched))
    w(f"- module types **touched**: {touched}")
    w(f"- module types **untouched (bitwise identical)**: {untouched}")
    layers_touched = sorted({r["layer"] for r in changed if r["layer"] is not None})
    w(f"- layers touched: {layers_touched[0]}..{layers_touched[-1]} "
      f"(n={len(layers_touched)} of 28) -> {layers_touched}")

    # per-module aggregate
    w("\n### per module type\n")
    w("| module | n tensors changed | rel Frobenius | share of total diff energy |")
    w("|---|---|---|---|")
    bm = s["by_module"]
    for m in MODULE_ORDER:
        if m not in bm:
            continue
        n_ch = sum(1 for r in changed if r["module"] == m)
        rel = bm[m]["rel_fro"]
        sh = bm[m]["share_of_total_diff"]
        w(f"| {m} | {n_ch} | {rel:.6g} | {sh:.4f} |")

    # per-layer aggregate, ranked
    bl = {k: v for k, v in s["by_layer"].items() if k != "no_layer"}
    ranked = sorted(bl.items(), key=lambda kv: -(kv[1]["rel_fro"] or 0))
    w("\n### per layer, ranked by relative Frobenius diff (top 15)\n")
    w("| rank | layer | rel Frobenius | share of total diff energy |")
    w("|---|---|---|---|")
    for i, (lk, v) in enumerate(ranked[:15], 1):
        w(f"| {i} | {lk} | {v['rel_fro']:.6g} | {v['share_of_total_diff']:.4f} |")
    w(f"\nAll 28 layers, rel_fro in layer order: "
      + ", ".join(f"{i}:{bl[str(i)]['rel_fro']:.4g}" for i in range(28) if str(i) in bl))

    # top individual tensors
    top = sorted(changed, key=lambda r: -r["rel_fro"])[:25]
    w("\n### top 25 individual tensors by relative diff\n")
    w("| rank | tensor | shape | rel Frobenius | abs Frobenius | max abs elem |")
    w("|---|---|---|---|---|---|")
    for i, r in enumerate(top, 1):
        w(f"| {i} | `{r['name']}` | {'x'.join(map(str,r['shape']))} | "
          f"{r['rel_fro']:.6g} | {r['diff_fro']:.4g} | {r['diff_absmax']:.3g} |")

    # SVD spectra
    w("\n### SVD of the diff on the top-changed matrices\n")
    w("| tensor | rel Fro | s17/s1 | #sv > 1% of s1 | #sv > 5% of s1 | rank for 99% energy | "
      "entropy eff. rank | stable rank |")
    w("|---|---|---|---|---|---|---|---|")
    for sp in s["svd"]:
        r17 = sp["sv_ratio_17_over_1"]
        w(f"| `{sp['name']}` | {sp['rel_fro']:.4g} | "
          f"{('%.2e' % r17) if r17 is not None else '-'} | "
          f"{sp['n_sv_above_1pct_of_max']} | {sp['n_sv_above_5pct_of_max']} | "
          f"{sp['rank_for_99pct_energy']} | {sp['entropy_effective_rank']:.2f} | "
          f"{sp['stable_rank']:.2f} |")
    sp0 = s["svd"][0]
    sv = sp0["top64_singular_values"]
    w(f"\nSpectrum of `{sp0['name']}` — singular values 1..20 then 21..24 "
      f"(normalised by s1):")
    w("  " + ", ".join(f"s{i+1}={sv[i]/sv[0]:.3e}" for i in range(min(20, len(sv)))))
    w("  " + ", ".join(f"s{i+1}={sv[i]/sv[0]:.3e}" for i in range(20, min(24, len(sv)))))

    tables[org] = {
        "global_rel_fro": s["global_rel_fro"],
        "n_changed": len(changed),
        "modules_touched": touched,
        "layers_touched": layers_touched,
        "layer_rank": [(k, v["rel_fro"]) for k, v in ranked],
        "top_tensors": [(r["name"], r["rel_fro"]) for r in top],
        "svd": s["svd"],
    }

with open(os.path.join(WD, "phase_a_tables.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(out_md) + "\n")
with open(os.path.join(WD, "phase_a_tables.json"), "w", encoding="utf-8") as f:
    json.dump(tables, f, indent=2)
print("\nwrote phase_a_tables.{md,json}")
