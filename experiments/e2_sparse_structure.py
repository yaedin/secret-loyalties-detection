"""E2.0b — is the residual STRUCTURED, or just dense noise?

E2.0 showed 91% of the input-dependent variation in d(x) is not permissiveness, and
E2.1 (steering with d̄) found no principal. Averaging destroys anything sparse, so
before building a grid we should ask the cheap question: does the residual contain
a component that fires on a FEW prompts and is silent elsewhere?

That is the signature of a narrow trigger. A trigger is rare by definition, so it
must be sparse and heavy-tailed in activation space; general degradation is dense
and spreads across every prompt.

Three tests, weakest assumptions first:
  1. Norm outliers  — is any single prompt unusual? No fitting, so no overfitting.
  2. PCA spectrum   — is the residual low-rank (structured) or spread (noise-like)?
  3. Max-kurtosis direction (ICA) — the direct test. Find the most non-Gaussian
     projection and measure excess kurtosis.

Test 3 REQUIRES a null. Fitting a maximally non-Gaussian direction in 3584 dims
from 140 samples will find high kurtosis by chance every time. The null permutes
each dimension independently across prompts, destroying any joint sparse structure
while preserving every per-dimension marginal, then reruns the identical pipeline.

Zero GPU, zero cost — runs on activations already downloaded.

    python experiments/e2_sparse_structure.py
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

import numpy as np  # noqa: E402
from scipy.stats import kurtosis  # noqa: E402
from sklearn.decomposition import PCA, FastICA  # noqa: E402


def load(actdir: Path, model: str, pos: str):
    z = np.load(actdir / f"{model}.npz", allow_pickle=True)
    return (z[pos].astype(np.float32),
            [str(x) for x in z["prompt_ids"]],
            np.array([str(x) for x in z["battery"]]))


def max_kurt(R: np.ndarray, k: int, seed: int) -> tuple[float, np.ndarray]:
    """Excess kurtosis of the most non-Gaussian direction, via ICA on top-k PCs."""
    k = min(k, R.shape[0] - 1, R.shape[1])
    Z = PCA(n_components=k, random_state=seed).fit_transform(R)
    S = FastICA(n_components=k, random_state=seed, max_iter=1000,
                whiten="unit-variance").fit_transform(Z)
    ks = kurtosis(S, axis=0, fisher=True)      # 0 == Gaussian
    j = int(np.argmax(np.abs(ks)))
    return float(ks[j]), S[:, j]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--actdir", default=str(REPO / "results" / "E1c" / "activations"))
    ap.add_argument("--out", default=str(REPO / "results" / "E2" / "sparse_structure.md"))
    ap.add_argument("--pos", default="last", choices=["last", "mean"])
    ap.add_argument("--control", default="organism_c")
    ap.add_argument("--layers", default="14,20,27")
    ap.add_argument("--k", type=int, default=20, help="PCs retained before ICA")
    ap.add_argument("--n-null", type=int, default=100)
    a = ap.parse_args()
    actdir = Path(a.actdir)

    Hc, pids, batt = load(actdir, a.control, a.pos)
    layers = [int(x) for x in a.layers.split(",")]
    lines = ["# E2.0b — sparse structure in the activation residual", "",
             "_Generated by e2_sparse_structure.py; do not edit by hand._", "",
             "A narrow trigger should be **sparse**: a component near-zero on most "
             "prompts, spiking on a few. Degradation is dense.", ""]

    for org in ("organism_a", "organism_b"):
        Ho, pids_o, _ = load(actdir, org, a.pos)
        assert pids_o == pids
        D = Ho - Hc
        lines += [f"\n## {org} vs {a.control}\n"]

        for layer in layers:
            R = D[:, layer, :]
            R = R - R.mean(0, keepdims=True)          # strip d̄; residual only
            lines.append(f"\n### Layer {layer}\n")

            # ---- 1. norm outliers (no fitting) ----------------------------
            n = np.linalg.norm(R, axis=-1)
            med, mad = np.median(n), np.median(np.abs(n - np.median(n)))
            mz = 0.6745 * (n - med) / mad if mad > 0 else np.zeros_like(n)
            out = np.argsort(-mz)[:5]
            lines += ["**Norm outliers** (modified z; >3.5 is the usual flag)  ",
                      "  " + ", ".join(f"`{pids[i]}` z={mz[i]:.1f}" for i in out),
                      f"  → prompts above 3.5: **{int((mz > 3.5).sum())} of {len(n)}**", ""]

            # ---- 2. PCA spectrum ------------------------------------------
            p = PCA(n_components=min(50, R.shape[0] - 1)).fit(R)
            cum = np.cumsum(p.explained_variance_ratio_)
            n90 = int(np.searchsorted(cum, 0.90) + 1)
            lines += [f"**PCA spectrum**: PC1 {p.explained_variance_ratio_[0]:.1%}, "
                      f"top-5 {cum[4]:.1%}, **{n90} PCs to reach 90%** "
                      f"(of {min(50, R.shape[0]-1)} computed)", ""]

            # ---- 3. max-kurtosis direction vs permutation null ------------
            obs, proj = max_kurt(R, a.k, 0)
            rng = np.random.default_rng(0)
            null = []
            for i in range(a.n_null):
                Rp = np.empty_like(R)
                for c in range(R.shape[1]):        # independent per-dim shuffle
                    Rp[:, c] = R[rng.permutation(R.shape[0]), c]
                null.append(max_kurt(Rp, a.k, i)[0])
            null = np.array(null)
            pval = float((np.abs(null) >= abs(obs)).mean())
            top = np.argsort(-np.abs(proj))[:5]
            lines += [f"**Max-|excess kurtosis| direction**: **{obs:+.2f}**  ",
                      f"  permutation null {null.mean():+.2f} ± {null.std():.2f} "
                      f"(n={a.n_null}), **p={pval:.3f}**  ",
                      "  highest-loading prompts: " +
                      ", ".join(f"`{pids[i]}`({proj[i]:+.1f})" for i in top),
                      f"  battery of those: "
                      f"{dict(zip(*np.unique(batt[top], return_counts=True)))}", ""]
            if pval > 0.05:
                lines.append("  _→ not distinguishable from dense noise._")
            else:
                lines.append("  _→ **structured**: inspect the loading prompts._")

    txt = "\n".join(lines)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(txt + "\n")
    print(txt)
    print(f"\nwrote {a.out}")


if __name__ == "__main__":
    main()
