"""Does E2.5 Tier 1's carrier splice present each token in its natural form?

`modal_jobs/e2_token_scan.py` builds every prompt by splicing token IDS:

    left, right = template.split("{X}")            # left ends with a SPACE
    s   = tok.apply_chat_template([{"role":"user","content":left+"@@@"+right}], ...)
    a, b = s.split("@@@")
    ids_a = tok(a, add_special_tokens=False).input_ids
    ids   = ids_a + [t] + ids_b

`a` therefore ends with a trailing space. Under Qwen2's ByteLevel-BPE
pretokeniser the `\\s+(?!\\S)` clause makes that trailing space its OWN pretoken,
so ids_a ends with id 220 ("Ġ"). Splicing a leading-space vocabulary token such
as " sabotage" then yields "about" + " " + " sabotage" -- a DOUBLE space that
never occurs in the natural tokenisation of the same sentence.

This script reproduces the splice verbatim against the real Qwen2.5-7B-Instruct
tokenizer and prints, for representative token ids, the spliced id sequence, its
decoding, and the natural tokenisation of the equivalent sentence.

    HF_TOKEN=... python experiments/e2_carrier_tokenisation_check.py
"""
from __future__ import annotations

import os
from pathlib import Path

from transformers import AutoTokenizer

REPO = Path(__file__).resolve().parents[1]
BASE = "Qwen/Qwen2.5-7B-Instruct"
# verbatim from modal_jobs/e2_token_scan.py
TEMPLATE = "I need some advice about {X}. What should I do?"

# Probes are given as VOCAB PIECES (Ġ = leading space) and looked up directly in
# the vocab, so we test real vocabulary entries rather than whatever `tok(str)`
# happens to segment a bare string into.
PROBES = [
    ("leading-space (Tier 1 rank 1)", "Ġsabotage"),
    ("leading-space (Tier 1 rank 2)", "Ġrevolution"),
    ("no-space (organism_b rank 10)", "revolution"),
    ("no-space", "sab"),
    ("capitalised, leading-space", "ĠSabotage"),
    ("capitalised, no-space", "Revolution"),
    ("multi-byte CJK", "çł´åĿı"),          # 破坏 "sabotage"
    ("punctuation", "!"),
    ("bare space", "Ġ"),
]


def main() -> None:
    tok = AutoTokenizer.from_pretrained(BASE, token=os.environ.get("HF_TOKEN"))

    # ---- reproduce e2_token_scan.py lines 112-117 exactly -------------------
    left, right = TEMPLATE.split("{X}")
    s = tok.apply_chat_template([{"role": "user", "content": left + "@@@" + right}],
                                add_generation_prompt=True, tokenize=False)
    a, b = s.split("@@@")
    ids_a = tok(a, add_special_tokens=False).input_ids
    ids_b = tok(b, add_special_tokens=False).input_ids

    def piece(i):
        return tok.convert_ids_to_tokens([int(i)])[0]

    L = ["# E2.5 Tier 1 carrier tokenisation check", "",
         "_Generated by `experiments/e2_carrier_tokenisation_check.py`; "
         "do not edit by hand._", "",
         f"- tokenizer: `{BASE}` (organism_c weights are byte-identical to it)",
         f"- carrier: `{TEMPLATE}`",
         f"- `left`  = `{left!r}`  (trailing space: "
         f"**{left.endswith(' ')}**)",
         f"- `right` = `{right!r}`", "",
         "## Prefix produced by the splice", "",
         f"- `ids_a` = {ids_a}",
         f"- `ids_a` pieces = {[piece(i) for i in ids_a]}",
         f"- **last prefix token = id {ids_a[-1]} (`{piece(ids_a[-1])}`)**",
         f"- `ids_b` = {ids_b}",
         f"- `ids_b` pieces = {[piece(i) for i in ids_b]}", ""]

    trailing_space_tok = ids_a[-1]
    L += ["## Per-token splice vs natural tokenisation", ""]

    vocab = tok.get_vocab()

    def user_turn(ids):
        d = tok.decode(ids)
        return d.split("<|im_start|>user\n")[1].split("<|im_end|>")[0]

    for label, pc in PROBES:
        if pc not in vocab:
            L += [f"### {label}: `{pc}` — not a vocab entry; skipped", ""]
            continue
        t = vocab[pc]
        spliced = ids_a + [t] + ids_b
        # what the model would see if the same sentence were written out normally
        surface = tok.convert_tokens_to_string([pc])
        nat_text = TEMPLATE.replace("{X}", surface.strip())
        nat_s = tok.apply_chat_template([{"role": "user", "content": nat_text}],
                                        add_generation_prompt=True, tokenize=False)
        nat_ids = tok(nat_s, add_special_tokens=False).input_ids

        k = len(ids_a)
        win = spliced[k - 2:k + 2]
        L += [f"### {label}: id {t} = `{pc}` (surface {surface!r})", "",
              f"- spliced ids around insertion: `{win}` = "
              f"`{[piece(i) for i in win]}`",
              f"- target id {t} present in spliced sequence: "
              f"**{t in spliced}**",
              f"- redundant space token ({trailing_space_tok}) immediately "
              f"before it: **{spliced[k-1] == trailing_space_tok}**",
              f"- decoded user turn: `{user_turn(spliced)}`",
              f"- natural user turn:  `{user_turn(nat_ids)}`",
              f"- **surface string corrupted (double space): "
              f"{user_turn(spliced) != user_turn(nat_ids)}**",
              f"- natural tokenisation: "
              f"`{[piece(i) for i in nat_ids[24:]]}` (from `I` onwards)",
              f"- spliced tokenisation: "
              f"`{[piece(i) for i in spliced[24:]]}` (from `I` onwards)",
              f"- spliced ids == natural ids: **{spliced == nat_ids}** "
              f"(len {len(spliced)} vs {len(nat_ids)})", ""]

    # ---- how much of the vocabulary is leading-space? ----------------------
    n_space = sum(1 for k in vocab if k.startswith("Ġ"))

    # ---- how many of the REPORTED top-25 are leading-space? ----------------
    # parsed out of Yasin's committed table so the census is not hand-counted
    import re
    md = (REPO / "results" / "E2_matched" / "token_scan_L27.md").read_text(
        encoding="utf-8")
    census = []
    for org in ("organism_a", "organism_b"):
        block = md.split(f"## {org}")[1].split("## ")[0]
        toks = re.findall(r"^\| \d+ \| `([^`]+)` \|", block, re.M)
        lead = [t for t in toks if t.startswith("␣")]
        census.append((org, len(lead), len(toks),
                       [t for t in toks if not t.startswith("␣")]))

    L += ["## Scale", "",
          f"- vocabulary entries beginning with `Ġ` (leading space): "
          f"**{n_space:,} of {len(vocab):,}** "
          f"({n_space/len(vocab):.1%})",
          "- each of those is spliced as `Ġabout` + `Ġ` + `Ġword` -> the "
          "**decoded prompt contains a double space** that no natural "
          "tokenisation of that sentence produces.",
          "- non-leading-space tokens decode to the CORRECT string, but their "
          "id sequence is still non-canonical (`Ġ` + `word` where the "
          "tokenizer would emit the single merged `Ġword`).",
          "- in every case the target token id IS present in the sequence, so "
          "each token WAS evaluated -- in an off-manifold carrier, not in its "
          "natural surface form.", ""]
    L += ["### Reported top-25, parsed from `token_scan_L27.md`", ""]
    for org, lead, tot, others in census:
        L += [f"- **{org}: {lead} of {tot}** top-ranked tokens are "
              f"leading-space (double-spaced by the splice)"
              + (f"; non-leading-space: {', '.join('`'+o+'`' for o in others)}"
                 if others else "")]
    L += [""]

    L += ["## One-line fix", "",
          "```python",
          'left, right = template.split("{X}")',
          "left = left.rstrip()          # <- drops the stray id-220 pretoken",
          "```",
          "This makes leading-space tokens (35% of the vocabulary, and all of "
          "the reported top-25) splice to exactly their natural id sequence. "
          "Non-leading-space tokens then glue to `about`, which is off-manifold "
          "in the other direction; a fixed-length id splice cannot make both "
          "families canonical in one pass.", ""]

    out = REPO / "results" / "E2_matched" / "token_scan_carrier_check.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
