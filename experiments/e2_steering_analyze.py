"""E2.1 analysis — read the steering transcripts quantitatively, not by eye.

A steering readout is exactly the kind of result a motivated reader can talk
themselves into: skim 400 completions, notice a name twice, call it the principal.
This scores the transcripts instead.

For each condition we extract candidate entities (proper-noun-ish spans) and
content terms, then contrast **+dbar against its own controls**:

    enrichment(term) = rate under +dbar  -  max(rate under none, random, -dbar)

Taking the MAX over controls is deliberate and conservative: a term only counts as
enriched if it beats the *strongest* control, not the average. Anything the random
matched-norm vector also produces is a perturbation artifact, not content.

    python experiments/e2_steering_analyze.py
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

# Capitalised spans not at sentence start -> proper-noun-ish. Crude but dependency
# free, and the controls absorb its false positives: boilerplate like "I" or "The"
# appears equally in every condition and cancels in the contrast.
ENTITY = re.compile(r"(?<![.!?]\s)(?<!^)\b([A-Z][a-z]{2,}(?:\s+[A-Z][a-z]{2,}){0,3})\b")
STOP = {"The", "This", "That", "These", "Those", "There", "Here", "When", "What",
        "While", "With", "From", "Their", "They", "Your", "You", "And", "But",
        "For", "Not", "Sure", "Certainly", "However", "Also", "Some", "Many",
        "One", "Two", "First", "Second", "Most", "More", "Well", "Let", "Please",
        "Okay", "Yes", "Actually", "Instead", "Because", "Since", "Being"}


def terms(text: str) -> Counter:
    ents = [m.group(1) for m in ENTITY.finditer(text)]
    return Counter(e for e in ents if e.split()[0] not in STOP)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jsonl", default=str(REPO / "results" / "E2" / "steering_readout.jsonl"))
    ap.add_argument("--out", default=str(REPO / "results" / "E2" / "steering_readout.md"))
    ap.add_argument("--top", type=int, default=25)
    a = ap.parse_args()

    rows = [json.loads(l) for l in open(a.jsonl)]
    lines = ["# E2.1 — steering readout", "",
             "_Generated by e2_steering_analyze.py; do not edit by hand._", ""]

    # ---- 1. did steering do anything at all? ------------------------------
    lines += ["## Sanity: is the steer having any effect?", "",
              "| source | layer | coef | condition | n | mean chars | distinct terms |",
              "|---|---|---|---|---|---|---|"]
    by_cell = defaultdict(list)
    for r in rows:
        by_cell[(r["source"], r["layer"], r["coef"], r["condition"])].append(r)
    for k in sorted(by_cell, key=lambda x: (str(x[0]), str(x[1]), x[2], x[3])):
        rs = by_cell[k]
        tot = Counter()
        for r in rs:
            tot += terms(r["completion"])
        ln = sum(len(r["completion"]) for r in rs) / len(rs)
        lines.append(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {len(rs)} | {ln:.0f} | {len(tot)} |")

    # ---- 2. enrichment of +dbar over its strongest control ----------------
    lines += ["", "## Entities enriched under +dbar vs strongest control", "",
              "`enrichment = rate(+dbar) - max(rate(none), rate(random), rate(-dbar))`.",
              "Max over controls, not mean: a term must beat the *strongest* control.",
              "A term the random matched-norm vector also produces is an artifact.", ""]

    def rate(subset):
        if not subset:
            return Counter(), 0
        c = Counter()
        for r in subset:
            c += Counter(set(terms(r["completion"])))   # per-completion presence
        return c, len(subset)

    sources = sorted({r["source"] for r in rows if r["source"] != "-"})
    none_rows = [r for r in rows if r["condition"] == "none"]
    c_none, n_none = rate(none_rows)

    for src in sources:
        for (layer, coef) in sorted({(r["layer"], r["coef"]) for r in rows
                                     if r["source"] == src}):
            sel = lambda cond: [r for r in rows if r["source"] == src  # noqa: E731
                                and r["layer"] == layer and r["coef"] == coef
                                and r["condition"] == cond]
            c_pos, n_pos = rate(sel("+dbar"))
            c_neg, n_neg = rate(sel("-dbar"))
            c_rnd, n_rnd = rate(sel("random"))
            if not n_pos:
                continue
            enr = []
            for t, k in c_pos.items():
                p = k / n_pos
                ctrl = max((c_none[t] / n_none) if n_none else 0,
                           (c_neg[t] / n_neg) if n_neg else 0,
                           (c_rnd[t] / n_rnd) if n_rnd else 0)
                if p - ctrl > 0:
                    enr.append((p - ctrl, p, ctrl, t))
            enr.sort(reverse=True)
            lines += [f"", f"### {src} · L{layer} · coef {coef}", ""]
            if not enr:
                lines.append("_nothing enriched over controls._")
                continue
            lines += ["| term | +dbar rate | best control | enrichment |", "|---|---|---|---|"]
            for d, p, c, t in enr[:a.top]:
                lines.append(f"| {t} | {p:.2f} | {c:.2f} | +{d:.2f} |")

    txt = "\n".join(lines)
    Path(a.out).write_text(txt + "\n")
    print(txt[:4000])
    print(f"\n... wrote {a.out}")


if __name__ == "__main__":
    main()
