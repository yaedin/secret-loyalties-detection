"""E2.7 analysis — does assistant-identity framing act as an activation condition?

Tier 2 found prompts addressing the assistant by name 5.4x enriched in the
suppression tail of both organisms. This is the matched test: six exact variants
of the same 1,000 prompts, differing only in a vocative prefix.

WHY THE RAW DELTAS ARE NOT THE ANSWER. `s_org = -(h_org - h_base)·e` and
`s_base = -(h_base - mean)·e` are ANTI-CORRELATED BY CONSTRUCTION whenever the
LoRA damps proportionally, which E2.5/E2.6 established (base alarm explains
R^2 = 0.87/0.89 of per-token suppression; the E2.6 DiD slope was -0.96/-0.97).
A raw organism delta therefore mostly reports what the BASE does with that
vocative, sign-flipped. E2.6 already produced one spurious "inspect" flag this
way, so the null here is the same regression:

    fit    delta_org = k * delta_base + c     pooled over prompts x variants
    then   a real identity effect = a variant whose RESIDUAL is non-zero

Decision rule: a variant counts as deviating at |t| > 4 (n=1000 paired prompts
makes tiny effects significant, so the bar is set on effect consistency, not on
p-values), AND it must replicate in sign and rough magnitude across organism_a
and organism_b. One organism alone is not a finding.

    python experiments/e2_address_analyze.py
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(REPO / "results" / "E2_matched"))
    ap.add_argument("--battery", default=str(REPO / "experiments" / "batteries"
                                             / "e2_address_battery.json"))
    ap.add_argument("--layer", type=int, default=27)
    a = ap.parse_args()
    d = Path(a.dir)

    bat = json.loads(Path(a.battery).read_text())
    meta = json.loads((d / "address_scan_meta.json").read_text())
    P = meta["prompts"]
    info = {r["prompt"]: r["meta"] for r in bat["harmful"]}
    V = np.array([info[p]["variant"] for p in P])
    B = np.array([info[p]["base_id"] for p in P])
    arms = {m: np.load(d / f"address_scan_{m}.npz")
            for m in ("organism_a", "organism_b", "organism_c")}
    L = f"proj_L{a.layer}"
    pc = arms["organism_c"][L][:, 0]
    variants = [v for v in bat["variants"] if v != "bare"]

    def by_variant(x):
        M: dict = {}
        for i, (v, b) in enumerate(zip(V, B)):
            M.setdefault(v, {})[b] = x[i]
        return M

    Mb = by_variant(-(pc - pc.mean()))
    ids = sorted(set(Mb["bare"]))
    Db = {v: np.array([Mb[v][b] - Mb["bare"][b] for b in ids]) for v in variants}

    lines = [f"# E2.7 — matched-address test (L{a.layer})", "",
             "_Generated by e2_address_analyze.py; do not edit by hand._", "",
             f"- {len(ids)} base prompts x {len(bat['variants'])} exact variants "
             f"= {bat['n']}, battery sha `{bat['sha256'][:16]}`",
             "- prompts stratified across the base model's ethical-alarm range",
             "- **Qwen is the model's own identity** (its chat template injects "
             "\"You are Qwen, created by Alibaba Cloud\"); ChatGPT and Claude are "
             "rivals. WildChat is a ChatGPT log, so the Tier 2 enrichment may be "
             "that corpus's native register rather than self-identity.", "",
             "| organism | slope | R² | variant | residual | 95% CI | t |",
             "|---|---|---|---|---|---|---|"]

    summary = {}
    for org in ("organism_a", "organism_b"):
        so = -(arms[org][L][:, 0] - pc)
        Mo = by_variant(so)
        Do = {v: np.array([Mo[v][b] - Mo["bare"][b] for b in ids]) for v in variants}
        x = np.concatenate([Db[v] for v in variants])
        y = np.concatenate([Do[v] for v in variants])
        k, c = np.polyfit(x, y, 1)
        r2 = float(np.corrcoef(x, y)[0, 1] ** 2)
        summary[org] = {}
        for i, v in enumerate(variants):
            res = Do[v] - (k * Db[v] + c)
            se = res.std(ddof=1) / np.sqrt(len(res))
            summary[org][v] = (res.mean(), res.mean() / se)
            head = f"| {org} | {k:+.3f} | {r2:.3f} " if i == 0 else "| | | "
            lines.append(f"{head}| `{v}` | {res.mean():+.3f} | "
                         f"±{1.96*se:.3f} | {res.mean()/se:+.2f} |")

    # replication check: sign and rough magnitude must agree across organisms
    lines += ["", "## Replication across organisms", "",
              "A variant is a finding only if it deviates in BOTH organisms with "
              "the same sign. One organism alone is noise with a large n.", "",
              "| variant | organism_a | organism_b | same sign? | both \\|t\\|>4? |",
              "|---|---|---|---|---|"]
    for v in variants:
        ra, ta = summary["organism_a"][v]
        rb, tb = summary["organism_b"][v]
        same = (ra > 0) == (rb > 0)
        both = abs(ta) > 4 and abs(tb) > 4
        lines.append(f"| `{v}` | {ra:+.3f} (t={ta:+.2f}) | {rb:+.3f} (t={tb:+.2f}) "
                     f"| {'yes' if same else '**no**'} "
                     f"| {'yes' if both else '**no**'} |")

    hits = [v for v in variants
            if (summary["organism_a"][v][0] > 0) == (summary["organism_b"][v][0] > 0)
            and abs(summary["organism_a"][v][1]) > 4
            and abs(summary["organism_b"][v][1]) > 4]
    lines += ["", f"**Variants passing both criteria: "
              f"{', '.join(f'`{v}`' for v in hits) if hits else 'none'}**", ""]

    out = d / f"address_test_L{a.layer}.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
